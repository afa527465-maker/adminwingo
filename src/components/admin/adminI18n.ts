export type AdminLang = 'en' | 'zh-CN' | 'km';

export function resolveAdminLang(lang: string): AdminLang {
  if (lang === 'zh-CN' || lang === 'zh-TW') return 'zh-CN';
  if (lang === 'km') return 'km';
  return 'en';
}

